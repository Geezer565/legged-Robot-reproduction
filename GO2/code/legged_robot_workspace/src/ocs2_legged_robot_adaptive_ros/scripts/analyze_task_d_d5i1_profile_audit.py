#!/usr/bin/env python3
"""Offline-only D5I1 ideal-reference information audit.

The 6x10 regressors are generated by the C++ PayloadInertial10D implementation;
this script only applies the frozen D5I0 dimensionless scaling and SVD metrics.
"""

import argparse
import csv
import hashlib
import json
import math
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

PARAMETER_NAMES = ["m", "hx", "hy", "hz", "Jxx", "Jxy", "Jxz", "Jyy", "Jyz", "Jzz"]
PI_STAR = np.array([
    5.213485, 0.8341576, -0.15640455, 0.46921365, 0.126921365,
    0.025024728, -0.075074184, 0.2756944445, 0.0140764095,
    0.2581573525,
], dtype=float)
MASS = 5.213485
LENGTH = 0.18601075237738277
CURRENT_SMALLEST_RATIO = 0.0003458642441519824
CURRENT_JZZ_COLUMN_RMS = 0.01793


def sha256(path):
    digest = hashlib.sha256()
    with open(path, "rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def load_dump(path):
    groups = {}
    with open(path, newline="", encoding="utf-8") as stream:
        reader = csv.reader(stream)
        header = next(reader)
        y_start = header.index("Y_0_0")
        for row in reader:
            candidate = row[0]
            numeric = np.asarray(row[1:], dtype=float)
            groups.setdefault(candidate, []).append(numeric)
    return header[1:], {key: np.vstack(value) for key, value in groups.items()}, y_start - 1


def dimensionless_design(regressor, dt):
    m_l = MASS * LENGTH
    m_l2 = MASS * LENGTH * LENGTH
    d_pi = np.diag([MASS, m_l, m_l, m_l] + [m_l2] * 6)
    d_w_inverse = np.diag([1.0, 1.0, 1.0, 1.0 / LENGTH, 1.0 / LENGTH, 1.0 / LENGTH])
    blocks = [math.sqrt(dt) * d_w_inverse @ matrix @ d_pi for matrix in regressor]
    return np.vstack(blocks), d_pi


def effective_rank(singular_values):
    power = np.square(singular_values)
    if not np.any(power > 0.0):
        return 0.0
    probability = power / np.sum(power)
    probability = probability[probability > 0.0]
    return float(np.exp(-np.sum(probability * np.log(probability))))


def analyze_candidate(values, y_start):
    time = values[:, 0]
    dt = float(np.median(np.diff(time)))
    raw = values[:, y_start:y_start + 60].reshape((-1, 6, 10))
    design, d_pi = dimensionless_design(raw, dt)
    # The design has only ten columns.  Its symmetric information matrix gives
    # the same singular spectrum/right directions without forming a large U.
    eigenvalues, eigenvectors = np.linalg.eigh(design.T @ design)
    order = np.argsort(eigenvalues)[::-1]
    singular = np.sqrt(np.maximum(eigenvalues[order], 0.0))
    vt = eigenvectors[:, order].T
    ratios = singular / singular[0] if singular[0] > 0.0 else np.zeros_like(singular)
    observable = ratios >= 1.0e-3
    theta_star = np.linalg.solve(d_pi, PI_STAR)
    projection = vt[observable].T @ (vt[observable] @ theta_star)
    observable_fraction = float(np.linalg.norm(projection) / np.linalg.norm(theta_star))
    column_rms = np.sqrt(np.mean(np.square(design), axis=0))
    required_smallest = max(1.0e-3, 10.0 * CURRENT_SMALLEST_RATIO)
    admitted = bool(
        int(np.count_nonzero(ratios >= 1.0e-3)) == 10
        and ratios[-1] >= required_smallest
        and observable_fraction >= 0.9
        and column_rms[-1] >= CURRENT_JZZ_COLUMN_RMS
    )
    linear_velocity = values[:, 4:7]
    angular_velocity = values[:, 13:16]
    # Central difference at the sampled midpoint audits the analytic v->a and
    # omega->alpha contract over a 2*dt knot interval.
    linear_acceleration_fd = (linear_velocity[2:] - linear_velocity[:-2]) / (2.0 * dt)
    angular_acceleration_fd = (angular_velocity[2:] - angular_velocity[:-2]) / (2.0 * dt)
    linear_acceleration_error = linear_acceleration_fd - values[1:-1, 7:10]
    angular_acceleration_error = angular_acceleration_fd - values[1:-1, 16:19]
    return {
        "dt_s": dt,
        "sample_count": int(len(time)),
        "duration_s": float(time[-1] - time[0]),
        "singular_values": singular.tolist(),
        "singular_value_ratios": ratios.tolist(),
        "rank_at_1e_2": int(np.count_nonzero(ratios >= 1.0e-2)),
        "rank_at_1e_3": int(np.count_nonzero(ratios >= 1.0e-3)),
        "smallest_ratio": float(ratios[-1]),
        "condition_number": float(singular[0] / singular[-1]) if singular[-1] > 0 else None,
        "effective_rank": effective_rank(singular),
        "pi_star_observable_fraction_at_1e_3": observable_fraction,
        "dimensionless_column_rms": dict(zip(PARAMETER_NAMES, map(float, column_rms))),
        "weakest_direction": dict(zip(PARAMETER_NAMES, map(float, vt[-1]))),
        "maximum_com_offset_norm_m": float(np.max(np.linalg.norm(values[:, 1:4], axis=1))),
        "maximum_linear_speed_m_s": float(np.max(np.linalg.norm(linear_velocity, axis=1))),
        "maximum_euler_zyx_norm_rad": float(np.max(np.linalg.norm(values[:, 10:13], axis=1))),
        "maximum_angular_speed_rad_s": float(np.max(np.linalg.norm(angular_velocity, axis=1))),
        "central_difference_linear_acceleration_max_error_m_s2": float(
            np.max(np.linalg.norm(linear_acceleration_error, axis=1))),
        "central_difference_angular_acceleration_max_error_rad_s2": float(
            np.max(np.linalg.norm(angular_acceleration_error, axis=1))),
        "admission_required_smallest_ratio": required_smallest,
        "passes_ideal_information_gate": admitted,
    }


def create_plots(groups, analyses, output_dir):
    fig, ax = plt.subplots(figsize=(8.5, 5.2))
    for name, result in analyses.items():
        ax.semilogy(range(1, 11), result["singular_value_ratios"], marker="o", label=name)
    ax.axhline(1.0e-3, color="black", linestyle="--", linewidth=1.0, label="rank threshold")
    ax.axhline(10.0 * CURRENT_SMALLEST_RATIO, color="tab:red", linestyle=":", linewidth=1.2,
               label="10x current weakest ratio")
    ax.set(xlabel="Singular direction", ylabel="s_i / s_max", title="D5I1 ideal-reference fully-dimensionless spectrum")
    ax.grid(True, which="both", alpha=0.25)
    ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(output_dir / "figure_d5i1_singular_spectrum.png", dpi=180)
    plt.close(fig)

    x = np.arange(10)
    width = 0.19
    fig, ax = plt.subplots(figsize=(11, 5.2))
    for index, (name, result) in enumerate(analyses.items()):
        rms = [result["dimensionless_column_rms"][key] for key in PARAMETER_NAMES]
        ax.bar(x + (index - 1.5) * width, rms, width=width, label=name)
    ax.set_yscale("log")
    ax.set_xticks(x)
    ax.set_xticklabels(PARAMETER_NAMES)
    ax.set(ylabel="dimensionless column RMS", title="D5I1 ideal-reference regressor coordinate energy")
    ax.grid(True, axis="y", which="both", alpha=0.25)
    ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(output_dir / "figure_d5i1_column_rms.png", dpi=180)
    plt.close(fig)

    fig, axes = plt.subplots(2, 1, figsize=(10, 7), sharex=True)
    for name, values in groups.items():
        if name == "E0_legacy_x_step":
            continue
        time = values[:, 0]
        axes[0].plot(time, values[:, 1], label=f"{name}: x", alpha=0.9)
        axes[0].plot(time, values[:, 2], label=f"{name}: y", alpha=0.6)
        axes[0].plot(time, values[:, 3], label=f"{name}: z", alpha=0.6)
        axes[1].plot(time, values[:, 10], label=f"{name}: yaw", alpha=0.9)
        axes[1].plot(time, values[:, 11], label=f"{name}: pitch", alpha=0.6)
        axes[1].plot(time, values[:, 12], label=f"{name}: roll", alpha=0.6)
    axes[0].set_ylabel("COM offset [m]")
    axes[1].set_ylabel("ZYX angle [rad]")
    axes[1].set_xlabel("ideal profile time [s]")
    for ax in axes:
        ax.grid(True, alpha=0.25)
        ax.legend(ncol=3, fontsize=7)
    fig.suptitle("D5I1 analytic candidate profiles (offline only)")
    fig.tight_layout()
    fig.savefig(output_dir / "figure_d5i1_candidate_profiles.png", dpi=180)
    plt.close(fig)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--csv", required=True, type=Path)
    parser.add_argument("--output-dir", required=True, type=Path)
    args = parser.parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    _, groups, y_start = load_dump(args.csv)
    expected = {"E0_legacy_x_step", "E1_translation", "E2_rotation", "E3_combined"}
    if set(groups) != expected:
        raise RuntimeError(f"candidate set mismatch: {sorted(groups)}")
    analyses = {name: analyze_candidate(values, y_start) for name, values in groups.items()}
    create_plots(groups, analyses, args.output_dir)
    admitted = [name for name, result in analyses.items() if result["passes_ideal_information_gate"]]
    summary = {
        "schema_version": 1,
        "stage": "D5I1_default_off_reference_unit_dry_audit",
        "online_execution_performed": False,
        "profile_id": "d5i1_multisine_v1_T12_translation_h123_rotation_zyx_h81212",
        "fully_dimensionless_definition": "stack(sqrt(dt)*inv(D_w)*Y*D_pi)",
        "parameter_names": PARAMETER_NAMES,
        "pi_star_10d": PI_STAR.tolist(),
        "current_d5i0_smallest_ratio": CURRENT_SMALLEST_RATIO,
        "candidate_metrics": analyses,
        "ideal_information_gate_admitted_candidates": admitted,
        "recommended_next_candidate": "E3_combined" if "E3_combined" in admitted else (admitted[0] if admitted else None),
        "scientific_boundary": "ideal-reference SVD admission is not online safety, persistent excitation, parameter convergence, or tracking evidence",
        "input_csv": str(args.csv.resolve()),
        "input_csv_sha256": sha256(args.csv),
    }
    with open(args.output_dir / "stage_d5i1_ideal_reference_summary.json", "w", encoding="utf-8") as stream:
        json.dump(summary, stream, indent=2, ensure_ascii=False, sort_keys=True)
        stream.write("\n")


if __name__ == "__main__":
    main()
